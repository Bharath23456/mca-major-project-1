@app.post("/api/v1/alerts/webhook", include_in_schema=False)
async def receive_alertmanager_webhook(
    payload: AlertManagerPayload,
    session: Session = Depends(get_session),
) -> dict[str, int]:
    """Accept Alertmanager events on the private Compose network."""
    for incoming in payload.alerts:
        labels = incoming.labels
        alert = session.scalar(
            select(AlertEvent).where(AlertEvent.fingerprint == incoming.fingerprint)
        )
        if alert is None:
            alert = AlertEvent(
                fingerprint=incoming.fingerprint, alertname=labels.get("alertname", "Unknown")
            )
            session.add(alert)
        alert.status = incoming.status
        alert.severity = labels.get("severity", "unknown")
        alert.instance = labels.get("instance", "")
        alert.summary = incoming.annotations.get("summary", "")
        alert.description = incoming.annotations.get("description", "")
        alert.starts_at = incoming.startsAt
        alert.ends_at = incoming.endsAt
        alert.labels_json = json.dumps(labels, sort_keys=True)
        alert.updated_at = datetime.now(UTC)
    session.commit()
    return {"received": len(payload.alerts)}


@app.get("/api/v1/monitoring/summary", tags=["monitoring"])
@app.get("/api/v1/metrics", tags=["monitoring"])
async def monitoring_summary() -> dict[str, Any]:
    queries = {
        **METRIC_QUERIES,
        "probe_success": "probe_success",
        "probe_duration_seconds": "probe_duration_seconds",
        "probe_http_status_code": "probe_http_status_code",
        "target_up": "up",
    }
    try:
        result_sets = await _query_many(queries)
    except PrometheusUnavailable as error:
        raise HTTPException(status_code=503, detail=str(error)) from error

    now = datetime.now(UTC).timestamp()
    metrics_data: dict[str, Any] = {}
    units = {
        "cpu_percent": "percent",
        "memory_percent": "percent",
        "disk_percent": "percent",
        "network_receive_bytes_per_second": "bytes_per_second",
        "network_transmit_bytes_per_second": "bytes_per_second",
        "system_uptime_seconds": "seconds",
    }
    for name, unit in units.items():
        series = result_sets[name]
        metrics_data[name] = [_series_value(item, now, unit) for item in series]
    endpoints = [
        {
            "endpoint": item.get("metric", {}).get("instance", "unknown"),
            "success": _series_value(item, now, "boolean"),
            "latency_seconds": _matching_value(
                result_sets["probe_duration_seconds"], item.get("metric", {}), now
            ),
            "http_status_code": _matching_value(
                result_sets["probe_http_status_code"], item.get("metric", {}), now
            ),
        }
        for item in result_sets["probe_success"]
    ]
    targets = [
        {
            "job": item.get("metric", {}).get("job", "unknown"),
            "instance": item.get("metric", {}).get("instance", "unknown"),
            "up": _series_value(item, now, "boolean"),
        }
        for item in result_sets["target_up"]
    ]
    return {
        "collected_at": datetime.now(UTC).isoformat(),
        "metrics": metrics_data,
        "endpoints": endpoints,
        "targets": targets,
        "source": "Prometheus",
        "missing_or_stale": (
            "Series with no current sample or older than 120 seconds are marked stale."
        ),
    }


@app.get("/api/v1/targets", tags=["monitoring"])
async def list_monitoring_targets() -> dict[str, Any]:
    try:
        results = await prometheus_query("up")
    except PrometheusUnavailable as error:
        return {
            "status": "unavailable",
            "targets": [],
            "source": "Prometheus",
            "reason": str(error),
        }

    now = datetime.now(UTC).timestamp()
    targets = [
        {
            "job": item.get("metric", {}).get("job", "unknown"),
            "instance": item.get("metric", {}).get("instance", "unknown"),
            "up": _series_value(item, now, "boolean"),
        }
        for item in results
    ]
    if not targets:
        status = "unavailable"
        reason = "Prometheus is reachable but has no target samples yet."
    elif any(
        target["up"]["stale"] or target["up"]["value"] != 1 for target in targets
    ):
        status = "degraded"
        reason = "One or more monitoring targets are down or have stale samples."
    else:
        status = "healthy"
        reason = None
    return {"status": status, "targets": targets, "source": "Prometheus", "reason": reason}


@app.get("/api/v1/overview", tags=["monitoring"])
async def monitoring_overview(session: Session = Depends(get_session)) -> dict[str, Any]:
    try:
        monitoring = await monitoring_summary()
        targets = monitoring["targets"]
        metrics = monitoring["metrics"]
        incomplete_metrics = any(
            not samples or any(sample["stale"] for sample in samples)
            for samples in metrics.values()
        )
        target_failure = any(
            target["up"]["stale"] or target["up"]["value"] != 1 for target in targets
        )
        state = "degraded" if incomplete_metrics or target_failure else "healthy"
        reason = (
            "Some telemetry is missing, stale, or reports a failed target."
            if state == "degraded"
            else None
        )
    except HTTPException as error:
        if error.status_code != 503:
            raise
        state = "degraded"
        reason = str(error.detail)
        monitoring = {
            "collected_at": None,
            "metrics": None,
            "endpoints": None,
            "targets": None,
            "source": "Prometheus",
        }
    return {
        "status": state,
        "reason": reason,
        "monitoring": monitoring,
        "anomaly_detection": anomaly_status(),
        "alerts": list_alerts(limit=50, offset=0, session=session),
        "anomalies": list_anomalies(limit=50, offset=0, session=session),
    }


@app.get("/api/v1/monitoring/history", tags=["monitoring"])
async def monitoring_history(
    metric: Literal[
        "cpu_percent",
        "memory_percent",
        "disk_percent",
        "network_receive_bytes_per_second",
        "network_transmit_bytes_per_second",
        "probe_duration_seconds",
        "probe_success",
    ] = "cpu_percent",
    hours: int = Query(default=6, ge=1, le=24),
) -> dict[str, Any]:
    expressions = HISTORY_QUERIES
    end = datetime.now(UTC).timestamp()
    start = end - hours * 3600
    step = max(15, hours * 3600 // 720)
    units = {
        "cpu_percent": "percent",
        "memory_percent": "percent",
        "disk_percent": "percent",
        "network_receive_bytes_per_second": "bytes_per_second",
        "network_transmit_bytes_per_second": "bytes_per_second",
        "probe_duration_seconds": "seconds",
        "probe_success": "boolean",
    }
    try:
        results = await prometheus_range_query(
            expressions[metric], start=start, end=end, step_seconds=step
        )
    except PrometheusUnavailable as error:
        raise HTTPException(status_code=503, detail=str(error)) from error

    series = []
    for result in results:
        points = []
        for timestamp, value in result.get("values", []):
            try:
                number = float(value)
            except (TypeError, ValueError):
                number = None
            if number is not None and not math.isfinite(number):
                number = None
            points.append(
                {
                    "timestamp": datetime.fromtimestamp(float(timestamp), UTC).isoformat(),
                    "value": number,
                    "stale": number is None,
                }
            )
        series.append(
            {
                "labels": result.get("metric", {}),
                "unit": units[metric],
                "points": points,
            }
        )
    return {
        "metric": metric,
        "unit": units[metric],
        "start": datetime.fromtimestamp(start, UTC).isoformat(),
        "end": datetime.fromtimestamp(end, UTC).isoformat(),
        "step_seconds": step,
        "series": series,
        "source": "Prometheus",
    }


async def _query_many(queries: dict[str, str]) -> dict[str, list[dict[str, Any]]]:
    import asyncio

    names = list(queries)
    results = await asyncio.gather(*(prometheus_query(queries[name]) for name in names))
    return dict(zip(names, results, strict=True))


def _series_value(series: dict[str, Any], now: float, unit: str | None = None) -> dict[str, Any]:
    value = series.get("value", [])
    if len(value) != 2:
        return {"value": None, "unit": unit, "timestamp": None, "stale": True}
    timestamp = float(value[0])
    age = max(0.0, now - timestamp)
    try:
        numeric_value = float(value[1])
    except (TypeError, ValueError):
        numeric_value = None
    if numeric_value is not None and not math.isfinite(numeric_value):
        numeric_value = None
    return {
        "value": numeric_value,
        "unit": unit,
        "timestamp": datetime.fromtimestamp(timestamp, UTC).isoformat(),
        "stale": age > 120 or numeric_value is None,
    }


def _utc_iso(value: datetime) -> str:
    if value.tzinfo is None:
        value = value.replace(tzinfo=UTC)
    return value.astimezone(UTC).isoformat()


def _matching_value(
    series: list[dict[str, Any]], labels: dict[str, str], now: float
) -> dict[str, Any]:
    for item in series:
        metric = item.get("metric", {})
        if metric.get("instance") == labels.get("instance"):
            return _series_value(item, now, "seconds")
    return {"value": None, "unit": "seconds", "timestamp": None, "stale": True}
