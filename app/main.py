@app.get("/health/ready", response_model=ReadinessResponse, tags=["health"])
async def readiness_check() -> ReadinessResponse | JSONResponse:
    """Report whether the database and Prometheus dependencies can answer."""
    checks: dict[str, Literal["ok", "unavailable"]] = {
        "database": "ok",
        "prometheus": "ok",
    }
    try:
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
    except SQLAlchemyError as error:
        checks["database"] = "unavailable"
        logger.warning(
            "Dependency readiness check failed",
            extra={
                "event": "readiness_dependency_failed",
                "dependency": "database",
                "error_type": type(error).__name__,
            },
        )

    try:
        await prometheus_query("up")
    except PrometheusUnavailable as error:
        checks["prometheus"] = "unavailable"
        logger.warning(
            "Dependency readiness check failed",
            extra={
                "event": "readiness_dependency_failed",
                "dependency": "prometheus",
                "error_type": type(error).__name__,
            },
        )

    if "unavailable" in checks.values():
        return JSONResponse(
            status_code=503,
            content=ReadinessResponse(status="degraded", checks=checks).model_dump(),
        )
    return ReadinessResponse(status="ready", checks=checks)


