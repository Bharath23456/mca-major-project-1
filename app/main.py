@app.get("/api/v1/config/validate", tags=["configuration"])
def validate_configuration() -> dict[str, Any]:
    thresholds = {
        "cpu_percent": settings.cpu_threshold_percent,
        "memory_percent": settings.memory_threshold_percent,
        "disk_percent": settings.disk_threshold_percent,
    }
    invalid = [name for name, value in thresholds.items() if not 0 < value <= 100]
    endpoint_count, endpoint_errors = validate_probe_targets(settings.blackbox_targets_path)
    try:
        prometheus_url = urlsplit(settings.prometheus_url)
        prometheus_valid = prometheus_url.scheme in {"http", "https"} and bool(
            prometheus_url.netloc
        )
    except ValueError:
        prometheus_valid = False
    errors = list(endpoint_errors)
    if not prometheus_valid:
        errors.append("Prometheus URL must be an HTTP or HTTPS URL with a host.")
    return {
        "valid": not invalid and not errors,
        "invalid_thresholds": invalid,
        "configured_thresholds_percent": thresholds,
        "endpoint_targets": {
            "valid": not endpoint_errors,
            "count": endpoint_count,
            "errors": endpoint_errors,
        },
        "prometheus_configured": prometheus_valid,
        "errors": errors,
    }


